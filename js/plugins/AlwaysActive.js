/*:
 * @target MZ
 * @plugindesc ゲームウィンドウが非アクティブでもゲーム更新を継続します。
 * @author Shadowgenic & Google Gemini
 *
 * @help
 * 【使い方】プラグイン管理で有効化するだけで、ゲーム画面が非アクティブでも更新を継続します。
 * オンライン待機やタイマー進行中に別ウィンドウへ切り替える場合に使用します。
 * ゲームウィンドウが別のウィンドウの背面にある場合でも、ゲームをアクティブ状態として扱います。
 * 画面更新と独立タイマーの更新を継続するため、オンラインセッションや待ち時間のあるゲームで使用します。
 * プラグインコマンドと設定項目はありません。
 *
 * 【使い方】
 * プラグイン管理画面で有効にするだけで動作します。ブラウザの省電力制御やOSの負荷制限までは解除できません。
 * 
 * 利用規約：無断で改変、再配布が可能。クレジット表記不要。
 */

(() => {
    'use strict';
    
    // 既存の機能：ウィンドウが非アクティブでも「アクティブ判定」にする
    SceneManager.isGameActive = function() {
        return true;
    };

    // 1秒間に60回（約16ms間隔）で強制更新を叩き続ける
    // シーン更新ではなく、タイマーのロジックだけを直接叩く
    setInterval(() => {
        if (typeof window.updateIndependentTimer === 'function') {
            window.updateIndependentTimer();
        }
    }, 1000 / 60);
})();